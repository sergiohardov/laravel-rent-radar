<?php

use App\Pipeline\EuroTwoRoomDetector;

it('finds a euro two-room flat however it is spelled', function (string $text) {
    expect((new EuroTwoRoomDetector)->matches($text))->toBeTrue();
})->with([
    'Сдам евродвушку на Палия',
    'Здам євродвушку довгостроково',
    '1-кімнатна квартира (євродвошка) площею 43 м²',
    'Евро-двушка в ЖК Море',
    'евро двушка, 6 жемчужина',
    'ЄВРО ДВУШКА',
    'Евродвухкомнатная квартира',
    'евро-двухкомнатная',
    'Здам євро двокімнатну квартиру',
    'Сдается евро 2-к квартира',
    'евро 2х на Каманина',
    'Сдам 2к евро возле моря',
    'двушка-евро в новом доме',
    'Кухня-студия и спальня в новом доме',
    'Простора кухня-студія та окрема спальня',
    'кухня гостиная, спальня с двуспальной кроватью',
    'Отдельная спальня, кухня-гостиная и зона для отдыха',
    'кухня-вітальня, спальня, гардероб',
    'Кухня-гостиная, в спальне шкаф-купе',
    'кухня-студія, у спальні кондиціонер',
]);

it('does not take other "euro" words or a plain one-room flat for it', function (string $text) {
    expect((new EuroTwoRoomDetector)->matches($text))->toBeFalse();
})->with([
    'Однокомнатная квартира с евроремонтом, 2 этаж',
    'Евро ремонт, двухкомнатная техника — нет',
    'евроокна, двушка рядом не сдаётся',
    'ЖК Новая Европа, однокімнатна квартира студійного типу',
    'Квартира-студия с кухней-студией',
    'Кухня-гостиная 20 м², санузел совмещён',
    'Сдам 1 комнатную, цена 400 евро, 2 этаж',
    'евро 2 этаж',
    'Кухня-студия, двуспальная кровать, санузел',
    'Кухня-гостиная и спальное место у окна',
    'кухня-студія, спальне місце на дивані',
]);

it('reads the title and the description together', function () {
    expect((new EuroTwoRoomDetector)->matches('Кухня-студия 18 м²', null, 'Окрема спальня з балконом'))->toBeTrue();
});
